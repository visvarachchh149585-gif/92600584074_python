# Program to illustrate data types and type casting

data_type1=10
print(type(data_type1))

a = 10
s = str(a)
print(s)
print(type(s))

s = '10'
a = int(s)
print(a)
print(type(a))

s = '10'
a = float(s)
print(a)
print(type(a))

l = [1,2,6,7]
t = tuple(l)
print(t)
print(type(t))
